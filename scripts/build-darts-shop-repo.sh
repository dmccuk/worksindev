#!/usr/bin/env bash
# Builds the darts-shop Git repo used in sprint 2, with its 2014 history, and
# writes it as a base64 tar.gz to src/game/assets/darts-shop-repo.ts.
#
# Building the history inside the in-browser VM takes about 12 Git commands
# at about 0.4 s each, so the game unpacks this archive instead.
# Run from the repo root: bash scripts/build-darts-shop-repo.sh
set -euo pipefail

out=src/game/assets/darts-shop-repo.ts
work=$(mktemp -d)
mkdir -p "$work/empty-template"
R="$work/darts-shop"
mkdir -p "$R"
git -C "$R" -c init.defaultBranch=main init -q --template="$work/empty-template"
git -C "$R" config core.logAllRefUpdates false

commit() {
	GIT_AUTHOR_NAME="$1" GIT_AUTHOR_EMAIL="$2@darts.example" GIT_AUTHOR_DATE="$3 +0100" \
	GIT_COMMITTER_NAME="$1" GIT_COMMITTER_EMAIL="$2@darts.example" GIT_COMMITTER_DATE="$3 +0100" \
		git -C "$R" -c core.autocrlf=false -c commit.gpgsign=false -c core.hooksPath=/dev/null commit -q -m "$4"
}
add() { git -C "$R" -c core.autocrlf=false add .; }

printf '# Darts Unlimited shop\nThe online shop. Ask Brant before changing anything. (Brant is on holiday.)\n' > "$R/README.md"
printf '<h1>Darts Unlimited</h1>\n<p>Open 9 to 5.</p>\n' > "$R/index.html"
printf 'item,price\ndartboard,49.99\ndarts (set of 3),12.50\noche mat,19.99\n' > "$R/prices.csv"
add && commit "Brant Holloway" brant "2014-09-01T10:00:00" "Initial shop"
printf '<h1>Checkout</h1>\n<p>Card payments only.</p>\n' > "$R/checkout.html"
add && commit "Kev Malone" kev "2014-09-15T14:20:00" "Add checkout page"
printf '<h1>Darts Unlimited</h1>\n<p>Open 9 to 6.</p>\n' > "$R/index.html"
add && commit "Sandra Price" sandra "2014-10-01T09:05:00" "Update opening hours"
printf 'DB_HOST=db01\nDB_PASSWORD=hunter2\n' > "$R/.env"
add && commit "Kev Malone" kev "2014-10-08T16:45:00" "Add database settings"
sed -i 's/dartboard,49.99/dartboard,4.99/' "$R/prices.csv"
add && commit "Tom" tom "2014-10-13T23:12:00" "testing discount"
printf '<h1>Darts Unlimited</h1>\n<p>Open 9 to 6. Free delivery over £50.</p>\n' > "$R/index.html"
add && commit "Kev Malone" kev "2014-10-14T11:30:00" "Fix typo on homepage"
git -C "$R" gc -q

# A clean Linux config (the build machine may add Windows-only settings).
printf '[core]\n\trepositoryformatversion = 0\n\tfilemode = true\n\tbare = false\n\tlogallrefupdates = true\n' > "$R/.git/config"

tar --force-local -C "$work" --owner=0 --group=0 -czf "$work/repo.tgz" darts-shop
{
	echo '// Generated by scripts/build-darts-shop-repo.sh. Do not edit.'
	echo '// The darts-shop Git repo for sprint 2, as a base64 tar.gz.'
	printf 'export const DARTS_SHOP_REPO =\n\t%s;\n' "'$(base64 -w0 "$work/repo.tgz")'"
} > "$out"
echo "Wrote $out ($(wc -c < "$work/repo.tgz") bytes compressed)"
git -C "$R" log --oneline
